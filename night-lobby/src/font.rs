pub fn supported(text: &str) -> bool {
    text.chars().all(|c| c == ' ' || glyph(c).is_some())
}

fn layout(text: &str, mut emit: impl FnMut(i32, Glyph)) -> i32 {
    let mut pen = 0;
    let mut adjacent = false;
    for c in text.chars() {
        if c == ' ' {
            pen += 3;
            adjacent = false;
            continue;
        }
        let g = glyph(c).unwrap_or_else(|| glyph('?').unwrap());
        pen += i32::from(adjacent);
        emit(pen, g);
        pen += g.0;
        adjacent = true;
    }
    pen
}

pub fn width(text: &str, scale: i32) -> i32 {
    layout(text, |_, _| {}) * scale
}

pub fn draw(p: &mut Pixels, x: i32, y: i32, text: &str, color: u32, scale: i32) {
    layout(text, |left, (width, top, rows)| {
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..width {
                if bits & (1 << col) != 0 {
                    p.rect(
                        x + (left + col) * scale,
                        y + (top + row as i32) * scale,
                        scale,
                        scale,
                        color,
                    );
                }
            }
        }
    });
}
